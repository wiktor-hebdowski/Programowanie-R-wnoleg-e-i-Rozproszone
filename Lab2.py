import numpy as np
import cupy as cp
import time
import matplotlib.pyplot as plt
import pycuda.driver as cuda
import pycuda.autoinit
from pycuda.compiler import SourceModule

sizes = [128, 256, 512, 1024, 2048]
times_cpu = []
times_cupy = []
times_pycuda = []

print("Wykonuję testy CPU (NumPy)...")
for N in sizes:
    A_cpu = np.random.rand(N, N).astype(np.float32)
    B_cpu = np.random.rand(N, N).astype(np.float32)

    t0 = time.time()
    _ = np.matmul(A_cpu, B_cpu)
    times_cpu.append(time.time() - t0)

print("Wykonuję testy GPU (CuPy)...")
_ = cp.matmul(cp.ones((10, 10), dtype=cp.float32), cp.ones((10, 10), dtype=cp.float32))

for N in sizes:
    A_cpu = np.random.rand(N, N).astype(np.float32)
    B_cpu = np.random.rand(N, N).astype(np.float32)
    A_cupy = cp.array(A_cpu)
    B_cupy = cp.array(B_cpu)

    t0 = time.time()
    _ = cp.matmul(A_cupy, B_cupy)
    cp.cuda.Stream.null.synchronize()
    times_cupy.append(time.time() - t0)

print("Wykonuję testy GPU (PyCUDA)...")
kernel_code = """
__global__ void matrixMul(float *A, float *B, float *C, int N) {
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    float sum = 0.0;
    if (row < N && col < N) {
        for (int k = 0; k < N; k++) {
            sum += A[row * N + k] * B[k * N + col];
        }
        C[row * N + col] = sum;
    }
}
"""
mod = SourceModule(kernel_code)
matrixMul = mod.get_function("matrixMul")

for N in sizes:
    A_cpu = np.random.rand(N, N).astype(np.float32)
    B_cpu = np.random.rand(N, N).astype(np.float32)
    C_cpu = np.empty((N, N), dtype=np.float32)

    t0 = time.time()
    A_gpu = cuda.mem_alloc(A_cpu.nbytes)
    B_gpu = cuda.mem_alloc(B_cpu.nbytes)
    C_gpu = cuda.mem_alloc(C_cpu.nbytes)
    cuda.memcpy_htod(A_gpu, A_cpu)
    cuda.memcpy_htod(B_gpu, B_cpu)

    block_size = (32, 32, 1)
    grid_size = (int(np.ceil(N / 32)), int(np.ceil(N / 32)), 1)
    matrixMul(A_gpu, B_gpu, C_gpu, np.int32(N), block=block_size, grid=grid_size)
    cuda.Context.synchronize()
    cuda.memcpy_dtoh(C_cpu, C_gpu)
    times_pycuda.append(time.time() - t0)

    del A_gpu, B_gpu, C_gpu

plt.figure(figsize=(9, 5))
plt.plot(sizes, times_cpu, label="CPU (NumPy)", marker='o')
plt.plot(sizes, times_cupy, label="GPU (CuPy)", marker='s')
plt.plot(sizes, times_pycuda, label="GPU (PyCUDA Kernel)", marker='^')

plt.xlabel("Rozmiar macierzy N x N")
plt.ylabel("Czas wykonania [s]")
plt.title("Porównanie wydajności mnożenia macierzy")
plt.legend()
